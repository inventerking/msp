package aigateway

import (
	"context"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"
)

// FakeProvider sends nothing outside the system (D-05). It returns deterministic replies that fit
// each task's schema, so features can be built and tested before a real provider is chosen. Tests
// can script it with Reply.
type FakeProvider struct {
	Reply func(ProviderRequest) (ProviderResponse, error)
}

// Key names the provider.
func (*FakeProvider) Key() string { return "fake_ai" }

var labelled = regexp.MustCompile(`(?m)^(Services|Pricing|Positioning|Regions|Industries|Technology):\s*(.+)$`)

var attributeFor = map[string]string{"Services": "service", "Pricing": "pricing", "Positioning": "positioning", "Regions": "geography", "Industries": "industry", "Technology": "technology"}

// Complete returns a reply for the task.
func (f *FakeProvider) Complete(_ context.Context, r ProviderRequest) (ProviderResponse, error) {
	if f.Reply != nil {
		return f.Reply(r)
	}
	var out any
	switch r.Task {
	case "lead_generation.explain_score":
		out = map[string]string{"explanation": "Fake explanation. " + firstLine(r.User)}
	case "competitor_intelligence.extract":
		// Pulls labelled lines from the page and quotes them exactly, as a careful model would.
		var obs []map[string]string
		for _, m := range labelled.FindAllStringSubmatch(r.User, 40) {
			for _, v := range strings.Split(m[2], ",") {
				if v = strings.TrimSpace(v); v != "" {
					obs = append(obs, map[string]string{"attribute_type": attributeFor[m[1]], "value": v, "quote": strings.TrimSpace(m[0])})
				}
			}
		}
		out = map[string]any{"observations": obs}
	case "competitor_intelligence.report":
		out = map[string]any{
			"summary":       "Fake market analysis. No AI provider is connected, so this text is a placeholder estimate.",
			"opportunities": []map[string]string{{"title": "Placeholder opportunity", "rationale": "Generated by the fake provider for testing.", "industry": "healthcare"}},
		}
	default:
		out = map[string]string{"summary": "Fake summary. No AI provider is connected."}
	}
	b, err := json.Marshal(out)
	if err != nil {
		return ProviderResponse{}, fmt.Errorf("fake reply: %w", err)
	}
	return ProviderResponse{Text: string(b), InputTokens: int32(len(r.User) / 4), OutputTokens: int32(len(b) / 4)}, nil //nolint:gosec // Test data.
}

func firstLine(s string) string {
	line, _, _ := strings.Cut(s, "\n")
	if len(line) > 200 {
		line = line[:200]
	}
	return line
}
